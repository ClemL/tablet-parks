/** The park deck for a game, base cards plus whichever expansions are on. */
export function parkDeckFor(expansions: { nightfall: boolean; wildlife: boolean }): ParkCard[] {
  return [
    ...PARKS,
    ...EXPANSION_PARKS.filter((p) => expansions[p.expansion]).map(({ expansion, ...card }) => {
      void expansion;
      return card;
    }),
  ];
}
